# Завдання 1 Напишіть додаток з чат ботом по допомозі з вивченням англійської мови.
#  Якщо користувач просить перекласти слово або фразу, то вивести переклад та приклад
# використання у речені  Якщо користувач просить перекласти речення, то вивести переклад
# та пояснення граматики, наприклад структура there is/are, пасивна форма дієслова, тощо

import os
import dotenv
import streamlit as st

from langchain_google_genai import ChatGoogleGenerativeAI

dotenv.load_dotenv()

gemini_api_key = os.getenv("GEMINI_API_KEY")

llm = ChatGoogleGenerativeAI(
    model="gemini-3.8-flash",
    api_key=gemini_api_key
)

st.title("English Language Assistant")

user_query = st.text_input("Введіть слово, фразу або речення:")

if user_query:
    prompt = f"""
    Ти помічник з вивчення англійської мови.

    Проаналізуй запит користувача.

    Якщо користувач просить перекласти слово або фразу:
    - дай переклад;
    - наведи приклад використання цього слова або фрази в англійському реченні;
    - дай переклад прикладу.

    Якщо користувач просить перекласти речення:
    - дай переклад;
    - поясни граматику речення;
    - поясни використані граматичні конструкції, наприклад there is/are,
      пасивну форму дієслова, час дієслова або інші важливі конструкції.

    Відповідай зрозуміло та допомагай користувачу вивчати англійську мову.

    Запит користувача:
    {user_query}
    """

    response = llm.invoke(prompt)

    st.write(response.content)